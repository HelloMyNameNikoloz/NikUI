'use strict';
const { EventEmitter } = require('events');
const { createDesktopNotifications, eventID } = require('../src/desktopNotifications');
module.exports = async () => {
  suite('One app-owned desktop publication ledger');
  const manager = new EventEmitter(), codex = new EventEmitter();
  const session = { id: 'conversation', provider: 'claude', items: [{ id: 'restored-result', kind: 'result', text: 'old' }] };
  manager.list = [session]; codex.list = [];
  let saved = { values: {} }, commits = 0, fail = false;
  const authority = { snapshot: () => structuredClone(saved), commit: async (fn) => {
    if (fail) throw Object.assign(new Error('fixture disk failure'), { code: 'STORAGE_UNAVAILABLE' });
    const next = structuredClone(saved); fn(next); saved = next; commits++;
  } };
  const options = { engine: { manager, codex }, engineID: 'a'.repeat(32), authority, now: () => 42 };
  let notifications = createDesktopNotifications(options); await notifications.flush();
  checkEqual('restored completed turns are not new notifications', notifications.snapshot().events, []);
  session.items.push({ id: 'approval-1', kind: 'permission', requestId: 'request-1', name: 'Bash' });
  manager.emit('changed'); await notifications.flush();
  const approval = notifications.snapshot();
  checkEqual('badge projects all unresolved approvals', approval.pendingApprovals.length, 1);
  checkEqual('approval event has stable engine/source identity', approval.events[0].id, eventID('a'.repeat(32), session.id, 'needs-you', ['approval-1', 'request-1', null, null, null, null]));
  manager.emit('changed'); await notifications.flush();
  checkEqual('repeated state changes publish once', notifications.snapshot().events.length, 1);
  const firstID = approval.events[0].id;
  await notifications.dispose(); notifications = createDesktopNotifications(options); await notifications.flush();
  checkEqual('restart retains event identity and durable deduplication', notifications.snapshot().events.map((e) => e.id), [firstID]);
  session.items[1].resolved = 'allow'; session.items.push({ id: 'result-2', kind: 'result', text: 'new result' });
  manager.emit('changed'); await notifications.flush();
  checkEqual('resolved approvals clear the badge', notifications.snapshot().pendingApprovals.length, 0);
  checkEqual('a new finished turn is published', notifications.snapshot().events.at(-1).kind, 'turn-finished');
  const finishedID = notifications.snapshot().events.at(-1).id;
  session.items.at(-1).at = 1000; manager.emit('changed'); await notifications.flush();
  check('reused renderer IDs cannot collapse distinct source result times', notifications.snapshot().events.at(-1).id !== finishedID);
  codex.list.push({ id: 'cx-one', provider: 'codex', items: [{ id: 'cx-error', kind: 'result', isError: true, text: 'failed' }] });
  codex.emit('changed'); await notifications.flush();
  checkEqual('Codex errors use the same publication path', notifications.snapshot().events.at(-1).kind, 'failed');
  check('stable IDs are shared with phone publication', notifications.identity('failed', { session: 'cx-one' }) === notifications.snapshot().events.at(-1).id);
  fail = true; session.items.push({ id: 'result-3', kind: 'result', text: 'must persist' }); manager.emit('changed'); await notifications.flush();
  checkEqual('failed persistence never publishes an uncommitted notification', [notifications.snapshot().issue, notifications.snapshot().events.some((e) => e.body === 'must persist')], ['STORAGE_UNAVAILABLE', false]);
  fail = false;
  saved.values[require('../src/desktopNotifications').KEY].seen = Array.from({ length: 4096 }, (_, i) => eventID('old', String(i), 'turn-finished', i));
  manager.emit('changed'); await notifications.flush();
  checkEqual('full publication window keeps accepting events', [notifications.snapshot().issue,
    saved.values[require('../src/desktopNotifications').KEY].seen.length, notifications.snapshot().events.some((e) => e.body === 'must persist')], [null, 4096, true]);
  const count = notifications.snapshot().events.length;
  manager.emit('changed'); await notifications.flush();
  checkEqual('rolling the window still deduplicates current candidates', notifications.snapshot().events.length, count);
  await notifications.dispose(); check('publication exercised durable commits', commits > 0);
};
